import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=name=>fs.readFileSync(new URL('../'+name,import.meta.url),'utf8');
const catalog=read('src/data/nationalDistrictMovement.ts');
const map=read('src/components/map/IntelligenceMap.tsx');
const source=read('src/services/boundaries.ts');
const dashboard=read('src/pages/Dashboard.tsx');
const detail=read('src/components/dashboard/NationwideDistrictPanel.tsx');
const items=[...catalog.matchAll(/\{ district: '([^']+)', governorate: '([^']+)' \}/g)].map(([,district])=>district);
assert.equal(items.length,26,'26 canonical ADM2 districts');
assert.equal(new Set(items).size,26,'unique district identities');
assert.ok(map.includes('nationalDistrictMovements.map(d=>{'),'all 26 represented by selectable SVG paths');
assert.ok(map.includes('onPointerDown={e=>e.stopPropagation()} onClick={()=>chooseDistrict(d)}'),'national district path clickable');
assert.ok(map.includes('nationalDistrictMovements.filter'),'search covers all 26');
assert.ok(map.includes('NATIONAL_CENTER')&&map.includes('NATIONAL_ZOOM'),'district map opens with Lebanon visible');
assert.ok(map.includes('resetMapToken'),'reset to all 26 via top map shortcut');
assert.ok(map.includes('Not separately reported'),'unlisted IOM figures never zero');
assert.ok(map.includes('districtDamageValue(d.district,damageMetric)'),'damage layer only where the selected published dataset has a value');
assert.ok(source.includes('loadAllDistrictBoundaries')&&source.includes('ALT_SERVICE'),'real ADM2 geometry with mirror fallback');
assert.ok(source.includes("if(Object.keys(collected).length===26)break;"),'full coverage detection');
assert.ok(dashboard.includes('NationwideDistrictPanel district={selectedDistrict}'),'23 other district panels supported');
assert.ok(dashboard.includes('selectedStudyDistrict ? <DistrictPanel'),'three Southern Lebanon detailed panels retained');
assert.ok(dashboard.includes("Show all 26 districts on map"),'shortcut points to map');
assert.ok(detail.includes('Returned TO district')&&detail.includes('Returnees departed FROM here'),'distinct return measures');
assert.ok(detail.includes('not separately reported'),'missing IOM data explained');
console.log('PASS: all 26 ADM2 map coverage, real geographic outlines, selection, search, IOM guardrails, existing 13 cadastres retained.');
