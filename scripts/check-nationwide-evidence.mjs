import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=(name)=>fs.readFileSync(new URL('../'+name,import.meta.url),'utf8');
const iom=JSON.parse(read('src/data/official/iomRound119.json'));
const undp=JSON.parse(read('src/data/official/undpSouth2026.json'));
const research=read('src/data/districtResearch.ts');
const layer=read('src/data/intelligenceLayers.ts');
const map=read('src/components/map/IntelligenceMap.tsx');
const dash=read('src/pages/Dashboard.tsx');
assert.equal(iom.idps_by_current_district.length,24);
assert.equal(iom.idps_by_district_of_origin.length,14);
assert.equal(iom.returnees_by_district_of_return.length,12);
assert.equal(iom.returnees_by_district_of_prior_displacement.length,18);
assert.equal(undp.district_debris_cost_estimates.length,5);
assert.equal((research.split('export const districtDamage2024:')[1].split('export const districtDamageJune2026:')[0].match(/affectedBuildings:\d+/g)||[]).length,15);
assert.equal((research.split('export const districtDamageJune2026:')[1].split('export const lookupDistrictPopulation')[0].match(/destroyed:\d+/g)||[]).length,3);
assert.match(layer,/metric==='affected2024'/);
assert.match(layer,/metric==='cost2026South'/);
assert.match(layer,/report.destroyed \+ report.partiallyDamaged/);
assert.match(layer,/colorForDamageCount/);
assert.ok(!map.includes('affected2024/16105*1_200_000_000'),'2024 buildings never misrepresented as fictional damage costs');
assert.match(map,/useState<PopulationMapMetric>\('hosted'\)/);
assert.match(map,/useState<DamageMapMetric>\('affected2024'\)/);
assert.match(map,/Unshaded = no published figure, not zero/);
assert.match(map,/damageMetricInfo.description/);
assert.match(dash,/useState<LayerId>\('population'\)/);
assert.ok(!layer.includes('return 0;'),'unreported IOM values are never forced to zero');
console.log('PASS — 26 district map; IOM hosting 24 / origin 14 / returns 12 / departures 18; UN damage 2024 15, South 2026 costs 5, Beirut+Mount counts 3; separate scales and no-data warnings.');
